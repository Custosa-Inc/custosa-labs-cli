#!/usr/bin/env node
/* Write the reference skill file from the evaluator's reference pack (T29 (l), T29-P2-C86; P1 C89).
 *
 *   node scripts/sync-reference.mjs <the evaluator's app/knowledge folder>
 *
 * The source is app/knowledge/reference in Custosa's private evaluator repository: regs.yaml (the 45 CFR paragraph per
 * practice, with its eCFR date), status.yaml (dated regulatory status) and vendors.yaml (one entry per service). This
 * writes skills/phi-schema-check-reference/SKILL.md with links and dates only: this package is public, so it carries
 * no BAA value, condition, status wording or excerpt (C89). The evaluator serves those, dated, in a finding's
 * reference part. test/reference-skill.test.mjs fails when the file differs from what this makes from core's pack.
 *
 * Release step: after the reference check-in (core RELEASE-CHECKLIST 7a), run this against the same evaluator
 * checkout as sync-rules, run npm test, and commit skills/. */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";

export const SKILL_FILE = resolve(dirname(fileURLToPath(import.meta.url)), "..", "skills", "phi-schema-check-reference", "SKILL.md");
const DAY = /^\d{4}-\d{2}-\d{2}$/;
const HTTPS = /^https:\/\/[^\s|()]+$/;

/* The pack's three files, as core's app/knowledge/reference.py loads them. */
export function readPack(knowledgeDir) {
  const load = (name, key) => YAML.parse(readFileSync(join(knowledgeDir, "reference", name), "utf8"))?.[key] ?? {};
  return { regs: load("regs.yaml", "practices"), status: load("status.yaml", "status"), vendors: load("vendors.yaml", "vendors") };
}

// One table row: the key, a link, and its date. Refuses what would not be a plain dated link.
function row(part, key, text, url, dateField, day) {
  const where = `${part} ${key}`;
  for (const [field, value] of [["key", key], [part === "regs" ? "cite" : "what", text]]) {
    if (!String(value ?? "").trim()) throw new Error(`${where}: no ${field}`);
    if (/[|\n[\]]/.test(String(value))) throw new Error(`${where}: ${field} has a | or a bracket or a line break`);
  }
  if (!HTTPS.test(String(url ?? ""))) throw new Error(`${where}: ${part === "regs" ? "url" : "source"} is not an https link`);
  if (!DAY.test(String(day ?? ""))) throw new Error(`${where}: ${dateField} is not a date`);
  return `| ${key} | [${text}](${url}) | ${day} |`;
}

const sorted = (entries) => Object.keys(entries).sort().map((k) => [k, entries[k]]);

/* The skill file's text. Only each entry's key, its link and the link's text (a cite, a title, or "source"), and
 * its date are read, so nothing else in the pack can reach the public package. */
export function renderReferenceSkill({ regs, status, vendors }) {
  const regRows = sorted(regs).map(([k, e]) => row("regs", k, e.cite, e.url, "as_of", e.as_of));
  const statusRows = sorted(status).map(([k, e]) => row("status", k, e.what, e.source, "checked_on", e.checked_on));
  // A vendor not read yet has `source: none` in core (upstash, dicebear): with no page to link, it is left out.
  const vendorRows = sorted(vendors).filter(([, e]) => e.source !== "none")
    .map(([k, e]) => row("vendors", k, "source", e.source, "checked_on", e.checked_on));
  return [
    "---",
    "name: phi-schema-check-reference",
    "description: Dated links to the HIPAA text behind each PHI Schema Check practice (45 CFR), to regulatory status pages, and to the page Custosa read for each listed vendor. Use it to cite or read the source a finding rests on. Links and dates only; a finding's reference part from check_schema carries the dated detail.",
    "---",
    "",
    "# PHI Schema Check reference links",
    "",
    "Generated by scripts/sync-reference.mjs from Custosa's reference pack. Do not edit by hand.",
    "",
    "Each date is when Custosa last read the page. Read the page itself before you rely on it. This file says nothing",
    "about whether a vendor signs a business associate agreement with this app, and nothing in it is evidence about this",
    "project: the check reads the project, and a finding's `reference` part carries the dated detail.",
    "",
    "## 45 CFR by practice",
    "",
    "| practice | cite | as of |",
    "| --- | --- | --- |",
    ...regRows,
    "",
    "## Regulatory status pages",
    "",
    "| what | page | checked |",
    "| --- | --- | --- |",
    ...statusRows,
    "",
    "## Vendor pages",
    "",
    "| service | page | checked |",
    "| --- | --- | --- |",
    ...vendorRows,
    "",
  ].join("\n");
}

function main(argv) {
  if (argv.length !== 1) {
    process.stderr.write("usage: node scripts/sync-reference.mjs <the evaluator's app/knowledge folder>\n");
    return 2;
  }
  const text = renderReferenceSkill(readPack(resolve(argv[0])));
  mkdirSync(dirname(SKILL_FILE), { recursive: true });
  writeFileSync(SKILL_FILE, text);
  process.stdout.write(`wrote ${SKILL_FILE}\n`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { process.exitCode = main(process.argv.slice(2)); } catch (err) { process.stderr.write(`sync-reference: ${err.message}\n`); process.exitCode = 1; }
}
